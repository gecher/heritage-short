"""COSTS.md from runs.jsonl: every call, failure, retry and cache hit, grouped by stage and model.

The numbers are measured, not estimated. Run `python -m pipeline report` after any build.
"""
from __future__ import annotations

import collections
import json
import statistics

from pipeline.common import ROOT, RUNS

FREE_LIMITS = {  # what I hit or read while building (see FAILURES.md); free tier, so $0 spent
    "gemini-4-hydrogen": "20 requests/day",
    "tts": "~10 requests/day per TTS model",
    "flux": "Cloudflare Workers AI free daily allocation (10,000 neurons)",
    "gemini": "per-model daily request limit; frequent 503 overload",
    "ffmpeg": "none (runs locally)",
}


def limit_for(model: str) -> str:
    m = (model or "").lower()
    if m in FREE_LIMITS:
        return FREE_LIMITS[m]
    if "tts" in m:
        return FREE_LIMITS["tts"]
    if "flux" in m:
        return FREE_LIMITS["flux"]
    if "ffmpeg" in m:
        return FREE_LIMITS["ffmpeg"]
    return FREE_LIMITS["gemini"] if "gemini" in m else ""


def run() -> None:
    rows = [json.loads(line) for line in RUNS.read_text(encoding="utf-8").splitlines() if line.strip()]
    groups: dict[tuple[str, str], list[dict]] = collections.defaultdict(list)
    for r in rows:
        if r.get("status") == "skipped":
            continue
        groups[(r.get("stage", "?"), r.get("model") or "cache")].append(r)
    lines = ["# Costs", "",
             f"Generated by `python -m pipeline report` from `runs.jsonl` ({len(rows)} lines, "
             f"{rows[0]['ts'][:10]} to {rows[-1]['ts'][:10]}). **Money spent: $0**: every provider was used on its free tier.",
             "", "| Stage | Model | OK | Errors | Rejected by quality gate | Cache hits | Median latency (s) | Total time (s) | Free limit found |",
             "|---|---|---|---|---|---|---|---|---|"]
    totals = collections.Counter()
    for (stage, model), rs in sorted(groups.items()):
        status = collections.Counter(r.get("status") for r in rs)
        ok = status["ok"]
        hits = status["hit"] + status["cache_hit"]
        lat = [r["latency_s"] for r in rs if r.get("status") == "ok" and r.get("latency_s") is not None]
        spent = sum(r.get("latency_s") or 0 for r in rs)
        totals.update(ok=ok, error=status["error"], rejected=status["rejected"], hits=hits)
        totals["seconds"] += spent
        lines.append(f"| {stage} | {model} | {ok} | {status['error']} | {status['rejected']} | {hits} | "
                     f"{statistics.median(lat):.1f} | {spent:.0f} | {limit_for(model)} |" if lat else
                     f"| {stage} | {model} | {ok} | {status['error']} | {status['rejected']} | {hits} | - | {spent:.0f} | {limit_for(model)} |")
    lines += ["", f"**Totals:** {totals['ok']} successful calls, {totals['error']} errors, "
                  f"{totals['rejected']} takes rejected by the quality gate, {totals['hits']} cache hits, "
                  f"{totals['seconds'] / 60:.0f} minutes waiting on providers.",
              "", "## What this shows",
              "- Most errors are not my bugs: they are overloaded free models (503) and daily quotas (429). "
              "Fallback chains turned them into delays instead of failures (FAILURES F03, F05).",
              "- Cache hits are calls that cost nothing: changing one shot rebuilds only that shot.",
              "- On the free tier the real constraint was requests per day and overloaded servers, not money."]
    (ROOT / "COSTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
